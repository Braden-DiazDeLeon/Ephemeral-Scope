"""Turning analysis results into Prolog facts.

The inference layer reasons over facts. A release note is a
paragraph of English that may contain quotes, backslashes, newlines and
Unicode; none of that belongs in a Prolog term. Each note is therefore given
a generated identifier -- ``change_1``, ``change_2`` -- and only the derived
properties cross the boundary:

    release_change(change_1, breaking_change).
    release_relevance(change_1, 0.85).
    classifier_agreement(change_1).

The text stays in Python, reachable through :attr:`FactBase.notes`, so the
report can quote it without Prolog ever having to parse it.

Everything that does become an atom goes through :func:`atom`, which quotes
and escapes rather than assuming the input is well behaved. 
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from pathlib import Path

from ephemeral_scope.domain.models import (
    AffectedUsage,
    ApiChange,
    ApiUsage,
    ClassifiedChange,
    DependencyUpgrade,
    EvidenceBundle,
    TestReference,
)

#: The atom naming the project under analysis. Fixed, because a fact file
#: describes exactly one analysis.
PROJECT_ATOM = "project"

#: An atom needs no quotes when it is a lowercase identifier. Anything else
#: -- paths, dotted symbols, versions, advisory ids -- gets quoted.
_BARE_ATOM = re.compile(r"^[a-z][a-zA-Z0-9_]*$")

#: Quoted atoms may not carry raw control characters; these have escapes.
_ESCAPES = {
    "\\": r"\\",
    "'": r"\'",
    "\n": r"\n",
    "\r": r"\r",
    "\t": r"\t",
    "\v": r"\v",
    "\f": r"\f",
    "\b": r"\b",
    "\0": r"\0",
}


def atom(value: object) -> str:
    """Render a Python value as a Prolog atom, quoting when necessary.

    Bare lowercase identifiers are emitted unquoted because that is how
    enum values such as ``removed`` and ``breaking_change`` read naturally
    in the rules. Everything else is single-quoted with backslash escapes.
    """
    text = "" if value is None else str(value)

    if _BARE_ATOM.match(text):
        return text

    escaped = []
    for character in text:
        if character in _ESCAPES:
            escaped.append(_ESCAPES[character])
        elif ord(character) < 0x20 or ord(character) == 0x7F:
            # Remaining control characters have no mnemonic escape.
            escaped.append(f"\\x{ord(character):x}\\")
        else:
            escaped.append(character)
    return "'" + "".join(escaped) + "'"


def number(value: float) -> str:
    """Render a float with a fixed precision so output is reproducible."""
    return f"{float(value):.4f}"


def fact(name: str, *arguments: str) -> str:
    """Assemble one clause, already-rendered arguments in, text out."""
    if not arguments:
        return f"{name}."
    return f"{name}({', '.join(arguments)})."


@dataclass(frozen=True, slots=True)
class FactBase:
    """The facts for one analysis, plus the prose they stand in for."""

    facts: tuple[str, ...] = ()
    #: change_N -> the statement it was generated from. Never sent to Prolog.
    notes: dict[str, str] = field(default_factory=dict)

    def to_prolog(self, header: str | None = None) -> str:
        """Render a loadable ``.pl`` fact file.

        Every predicate is declared dynamic so the file loads cleanly even
        when an analysis produced no facts for it; without that, a rule
        referring to an absent predicate raises an existence error instead
        of simply failing.
        """
        lines = ["%% Generated by ephemeral_scope.inference.fact_builder."]
        if header:
            lines += [f"%% {line}" for line in header.splitlines()]
        lines.append("")

        declarations = sorted({_signature(clause) for clause in self.facts})
        if declarations:
            lines += [f":- dynamic {declaration}." for declaration in declarations]
            lines.append("")

        lines += list(self.facts)
        return "\n".join(lines) + "\n"

    def write(self, path: Path, header: str | None = None) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.to_prolog(header), encoding="utf-8")
        return path


def _signature(clause: str) -> str:
    """``foo('a', 1).`` -> ``foo/2``; used to emit dynamic declarations."""
    head, _, rest = clause.partition("(")
    if not rest:
        return f"{clause.rstrip('.')}/0"
    return f"{head}/{_arity(rest.rstrip(').'))}"


def _arity(arguments: str) -> int:
    """Count top-level commas, ignoring any inside quoted atoms."""
    depth = 0
    quoted = False
    escaped = False
    count = 1
    for character in arguments:
        if escaped:
            escaped = False
        elif character == "\\":
            escaped = True
        elif character == "'":
            quoted = not quoted
        elif quoted:
            continue
        elif character in "([":
            depth += 1
        elif character in ")]":
            depth -= 1
        elif character == "," and depth == 0:
            count += 1
    return count


class FactBuilder:
    """Converts analysis results into a :class:`FactBase`.

    Each ``add_*`` method is independent, so a caller with only static
    results can emit those and skip the evidence entirely. Facts are
    deduplicated and emitted in insertion order, which keeps the generated
    file stable between runs on unchanged input.
    """

    def __init__(self, project: str = PROJECT_ATOM) -> None:
        self.project = project
        self._facts: dict[str, None] = {}
        self._notes: dict[str, str] = {}
        self._change_ids: dict[int, str] = {}

    def _emit(self, clause: str) -> None:
        self._facts.setdefault(clause, None)

    def build(self) -> FactBase:
        return FactBase(facts=tuple(self._facts), notes=dict(self._notes))

    def add_upgrade(self, upgrade: DependencyUpgrade) -> FactBuilder:
        """State what is being upgraded, and from where to where."""
        self._emit(fact("package", atom(upgrade.package_name)))
        self._emit(
            fact(
                "upgrade",
                atom(upgrade.package_name),
                atom(upgrade.current_version),
                atom(upgrade.target_version),
            )
        )
        return self

    def add_usages(self, usages: Iterable[ApiUsage]) -> FactBuilder:
        for usage in usages:
            self._emit(fact("uses_symbol", atom(self.project), atom(usage.symbol)))
            self._emit(
                fact(
                    "usage_site",
                    atom(_relative(usage.file)),
                    str(usage.line),
                    atom(usage.symbol),
                    atom(usage.usage_kind),
                )
            )
        return self

    def add_api_changes(self, changes: Iterable[ApiChange]) -> FactBuilder:
        for change in changes:
            self._emit(
                fact("api_change", atom(change.symbol), atom(change.change_type))
            )
        return self

    def add_affected_usages(self, affected: Iterable[AffectedUsage]) -> FactBuilder:
        """The join of project usage and API change: the core finding."""
        for item in affected:
            self._emit(
                fact(
                    "affected_usage",
                    atom(_relative(item.usage.file)),
                    str(item.usage.line),
                    atom(item.usage.symbol),
                    atom(item.change.change_type),
                )
            )
        return self

    def add_classified_changes(
        self, changes: Sequence[ClassifiedChange]
    ) -> FactBuilder:
        """Emit one identified statement per classified release note.

        The prose is withheld deliberately: only the category, the relevance
        score and the provenance of the decision cross into Prolog.
        """
        for change in changes:
            identifier = self._change_id(change)
            self._notes[identifier] = change.note.text

            if change.category is not None:
                self._emit(
                    fact("release_change", identifier, atom(change.category))
                )
            else:
                # Distinct from IRRELEVANT: nothing could categorise it.
                self._emit(fact("release_unclassified", identifier))

            self._emit(
                fact("release_relevance", identifier, number(change.relevance_score))
            )
            for symbol in change.matched_project_symbols:
                self._emit(fact("release_mentions", identifier, atom(symbol)))

            self._add_decision_facts(identifier, change)
        return self

    def _add_decision_facts(
        self, identifier: str, change: ClassifiedChange
    ) -> None:
        decision = change.decision
        if decision is None:
            return

        self._emit(
            fact(
                "classification_source",
                identifier,
                atom(decision.selection_reason),
            )
        )
        if decision.agreement:
            self._emit(fact("classifier_agreement", identifier))
        if decision.is_model_only:
            # Rules consult this to refuse escalating an uncorroborated
            # statistical guess to a high-risk finding.
            self._emit(fact("model_only", identifier))

    def _change_id(self, change: ClassifiedChange) -> str:
        key = id(change)
        if key not in self._change_ids:
            self._change_ids[key] = f"change_{len(self._change_ids) + 1}"
        return self._change_ids[key]

    def add_evidence(
        self, upgrade: DependencyUpgrade, evidence: EvidenceBundle
    ) -> FactBuilder:
        """Record which version each advisory affects.

        ``vulnerable_version`` and ``fixed_version`` are separate predicates
        so the rules can tell "the upgrade removes this exposure" from "the
        upgrade keeps it", which is the difference between a reason to
        upgrade and a reason to hesitate.
        """
        package = atom(upgrade.package_name)
        still_open = {
            record.vulnerability_id for record in evidence.target_vulnerabilities
        }

        for record in evidence.current_vulnerabilities:
            self._emit(
                fact(
                    "vulnerable_version",
                    package,
                    atom(upgrade.current_version),
                    atom(record.vulnerability_id),
                )
            )
            if record.vulnerability_id not in still_open:
                self._emit(
                    fact(
                        "fixed_version",
                        package,
                        atom(upgrade.target_version),
                        atom(record.vulnerability_id),
                    )
                )

        for record in evidence.target_vulnerabilities:
            self._emit(
                fact(
                    "vulnerable_version",
                    package,
                    atom(upgrade.target_version),
                    atom(record.vulnerability_id),
                )
            )
        return self

    def add_test_references(
        self, references: Iterable[TestReference]
    ) -> FactBuilder:
        for reference in references:
            self._emit(
                fact(
                    "test_covers",
                    atom(_relative(reference.test_file)),
                    atom(_relative(reference.source_file)),
                )
            )
        return self


def _relative(path: Path) -> str:
    return path.as_posix()


def build_facts(
    upgrade: DependencyUpgrade,
    usages: Sequence[ApiUsage] = (),
    api_changes: Sequence[ApiChange] = (),
    affected: Sequence[AffectedUsage] = (),
    classified_changes: Sequence[ClassifiedChange] = (),
    evidence: EvidenceBundle | None = None,
    test_references: Sequence[TestReference] = (),
    project: str = PROJECT_ATOM,
) -> FactBase:
    """Build the full fact base for one analysis."""
    builder = FactBuilder(project=project)
    builder.add_upgrade(upgrade)
    builder.add_usages(usages)
    builder.add_api_changes(api_changes)
    builder.add_affected_usages(affected)
    builder.add_classified_changes(classified_changes)
    if evidence is not None:
        builder.add_evidence(upgrade, evidence)
    builder.add_test_references(test_references)
    return builder.build()
